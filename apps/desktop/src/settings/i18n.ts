const dicts: Record<Language, Dictionary> = { en, zh };
const listeners = new Set<() => void>();
let currentLang: Language = (localStorage.getItem("coevo-lang") as Language) === "zh" ? "zh" : "en";

export function setLanguage(lang: Language) {
  currentLang = lang;
  try { localStorage.setItem("coevo-lang", lang); } catch {}
  listeners.forEach((listener) => listener());
}

export function getLanguage(): Language {
  return currentLang;
}

export function subscribeLanguage(listener: () => void) {
  listeners.add(listener);
  return () => listeners.delete(listener);
}

export function useLanguage(): Language {
  return useSyncExternalStore(subscribeLanguage, getLanguage, getLanguage);
}

export function t(key: string): string {
  return dicts[currentLang]?.[key] || en[key] || key;
}
